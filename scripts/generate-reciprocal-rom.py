#!/usr/bin/env python3
"""Generate fixed reciprocal seed INIT images; no runtime GPU division."""
import argparse
from pathlib import Path


def rne(numerator, denominator):
    quotient, remainder = divmod(numerator, denominator)
    return quotient + (2 * remainder > denominator or
                       (2 * remainder == denominator and quotient & 1))


def generate(root):
    base = [rne(1 << 43, 513 + 2 * i) for i in range(256)]
    gradient = [rne(1 << 34, (513 + 2 * i) ** 2) for i in range(256)]
    lines = ["// Generated by scripts/generate-reciprocal-rom.py; do not edit.",
             "#pragma once", "#include <array>", "#include <cstdint>",
             "namespace nano_gpu::hw {",
             "inline constexpr std::array<std::uint64_t, 256> reciprocal_seed_base{{"]
    for i in range(0, 256, 4):
        lines.append("    " + ", ".join(str(v) + "ULL" for v in base[i:i + 4]) + ",")
    lines.extend(["}};", "inline constexpr std::array<std::uint16_t, 256> reciprocal_seed_gradient{{"])
    for i in range(0, 256, 8):
        lines.append("    " + ", ".join(str(v) for v in gradient[i:i + 8]) + ",")
    lines.extend(["}};", "} // namespace nano_gpu::hw", ""])
    result = {root / "reference/include/nano_gpu/hw/reciprocal_seed.hpp": "\n".join(lines)}
    for bank in range(4):
        values = [(v >> (16 * bank)) & 0xffff for v in base] if bank < 3 else gradient
        result[root / f"rtl/generated/reciprocal_seed_{bank}.hex"] = "".join(f"{v:04x}\n" for v in values)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    failed = []
    for path, data in generate(root).items():
        if args.check:
            if not path.exists() or path.read_text() != data:
                failed.append(str(path.relative_to(root)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(data)
    if failed:
        raise SystemExit("Reciprocal seed files differ: " + ", ".join(failed))


if __name__ == "__main__":
    main()
